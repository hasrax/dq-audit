"""Render a small Markdown subset to Word (.docx) and PDF.

Both the standard audit report and AI-written custom reports are produced
as Markdown, so one renderer keeps the two formats identical. Supported:
# / ## / ### headings, paragraphs, - or * bullets, 1. numbered items,
**bold** inline, and | pipe | tables |. Pure-Python libraries only
(python-docx, fpdf2), so it runs on a small hosted server too.
"""
from __future__ import annotations

import io
import re
from datetime import datetime

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor
from fpdf import FPDF

ACCENT = (46, 125, 99)       # sage (light theme), readable on white paper
TEXT = (30, 33, 39)
MUTED = (91, 98, 112)
BOLD_RE = re.compile(r"(\*\*[^*]+\*\*)")
TABLE_SEP_RE = re.compile(r"^\|?\s*:?-{2,}")


def parse(md: str) -> list[tuple]:
    """Markdown -> blocks: (kind, payload)."""
    blocks: list[tuple] = []
    lines = md.replace("\r\n", "\n").split("\n")
    i, para = 0, []

    def flush():
        if para:
            blocks.append(("p", " ".join(para)))
            para.clear()

    while i < len(lines):
        line = lines[i].rstrip()
        stripped = line.strip()
        if not stripped:
            flush()
        elif stripped.startswith("#"):
            flush()
            level = len(stripped) - len(stripped.lstrip("#"))
            blocks.append(("h", min(level, 3), stripped.lstrip("#").strip()))
        elif stripped.startswith("|"):
            flush()
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not TABLE_SEP_RE.match(lines[i].strip()):
                    rows.append(cells)
                i += 1
            blocks.append(("table", rows))
            continue
        elif re.match(r"^[-*•]\s+", stripped):
            flush()
            blocks.append(("li", re.sub(r"^[-*•]\s+", "", stripped)))
        elif re.match(r"^\d+[.)]\s+", stripped):
            flush()
            blocks.append(("oli", stripped))
        else:
            para.append(stripped)
        i += 1
    flush()
    return blocks


def _runs(text: str) -> list[tuple[str, bool]]:
    return [(part[2:-2], True) if part.startswith("**") and part.endswith("**") else (part, False)
            for part in BOLD_RE.split(text) if part]


# --- Word ---------------------------------------------------------------------

def to_docx(md: str, footer: str = "") -> bytes:
    doc = Document()
    normal = doc.styles["Normal"]
    normal.font.name, normal.font.size = "Calibri", Pt(11)
    normal.font.color.rgb = RGBColor(*TEXT)
    for name in ("Title", "Heading 1", "Heading 2", "Heading 3"):
        doc.styles[name].font.color.rgb = RGBColor(*ACCENT)

    def add_runs(par, text):
        for chunk, bold in _runs(text):
            par.add_run(chunk).bold = bold

    for block in parse(md):
        kind = block[0]
        if kind == "h":
            doc.add_heading(block[2], level=0 if block[1] == 1 else block[1] - 1)
        elif kind == "p":
            add_runs(doc.add_paragraph(), block[1])
        elif kind == "li":
            add_runs(doc.add_paragraph(style="List Bullet"), block[1])
        elif kind == "oli":
            add_runs(doc.add_paragraph(), block[1])
        elif kind == "table" and block[1]:
            rows = block[1]
            width = max(len(r) for r in rows)
            table = doc.add_table(rows=0, cols=width)
            table.style = "Light Grid Accent 1"
            for r_idx, row in enumerate(rows):
                cells = table.add_row().cells
                for c_idx in range(width):
                    par = cells[c_idx].paragraphs[0]
                    for chunk, bold in _runs(row[c_idx] if c_idx < len(row) else ""):
                        par.add_run(chunk).bold = bold or r_idx == 0
            doc.add_paragraph()
    footer_par = doc.sections[0].footer.paragraphs[0]
    footer_par.text = footer or f"Generated by ClarityDQ on {datetime.now():%d %b %Y %H:%M}"
    footer_par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


# --- PDF ----------------------------------------------------------------------

_LATIN = str.maketrans({"·": "-", "—": "-", "–": "-", "“": '"', "”": '"', "‘": "'", "’": "'", "…": "...",
                        "×": "x", "≤": "<=", "≥": ">=", "→": "->", "▲": "^", "▼": "v", "■": "-", "•": "-",
                        "✓": "OK", "✕": "x", " ": " ", " ": " "})


def _latin(text: str) -> str:
    """Core PDF fonts are Latin-1; map common typography and replace the rest
    (keeps the PDF dependency-free -- no bundled font files)."""
    return text.translate(_LATIN).encode("latin-1", "replace").decode("latin-1")


class _PDF(FPDF):
    footer_text = ""

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", size=8)
        self.set_text_color(*MUTED)
        self.cell(0, 8, _latin(f"{self.footer_text}   ·   page {self.page_no()}"), align="C")


def to_pdf(md: str, footer: str = "") -> bytes:
    pdf = _PDF(format="A4")
    pdf.footer_text = footer or f"Generated by ClarityDQ on {datetime.now():%d %b %Y %H:%M}"
    pdf.set_margins(18, 16, 18)
    pdf.set_auto_page_break(True, margin=18)
    pdf.add_page()
    width = pdf.w - pdf.l_margin - pdf.r_margin
    for block in parse(md):
        kind = block[0]
        pdf.set_text_color(*TEXT)
        if kind == "h":
            size = {1: 18, 2: 14, 3: 12}[block[1]]
            pdf.ln(2 if block[1] > 1 else 0)
            pdf.set_font("Helvetica", "B", size)
            pdf.set_text_color(*ACCENT)
            pdf.multi_cell(width, size * 0.55, _latin(block[2]))
            pdf.ln(1)
        elif kind in ("p", "li", "oli"):
            pdf.set_font("Helvetica", size=10.5)
            text = _latin(block[1])
            if kind == "li":
                pdf.set_x(pdf.l_margin + 4)
                pdf.multi_cell(width - 4, 5.6, "- " + text, markdown=True)
            else:
                pdf.multi_cell(width, 5.6, text, markdown=True)
            pdf.ln(1.5)
        elif kind == "table" and block[1]:
            pdf.set_font("Helvetica", size=9.5)
            rows = block[1]
            cols = max(len(r) for r in rows)
            with pdf.table(width=width, line_height=5.5, first_row_as_headings=True) as table:
                for row in rows:
                    cells = table.row()
                    for c in range(cols):
                        cells.cell(_latin((row[c] if c < len(row) else "").replace("**", "")))
            pdf.ln(3)
    return bytes(pdf.output())
